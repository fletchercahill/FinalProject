public class PowerUp
{
    // =====================================================
    // POSITION
    // =====================================================

    private int x;
    private int y;

    // =====================================================
    // MOVEMENT
    // =====================================================

    private int dx = 4;
    private int dy = 3;

    // =====================================================
    // SIZE
    // =====================================================

    private int size = 60;

    // =====================================================
    // CONSTRUCTOR
    // =====================================================

    public PowerUp(int x, int y)
    {
        this.x = x;
        this.y = y;
    }

    // =====================================================
    // UPDATE MOVEMENT
    // =====================================================

    public void update()
    {
        x += dx;
        y += dy;

        // Bounce off left/right walls
        if (x <= 0 || x >= 1200 - size)
        {
            dx *= -1;
        }

        // Bounce off top/bottom walls
        if (y <= 0 || y >= 500 - size)
        {
            dy *= -1;
        }
    }

    // =====================================================
    // COLLISION
    // =====================================================

    public boolean collides(Player p)
    {
        return p.getX() < x + size &&
                p.getX() + 230 > x &&
                p.getY() < y + size &&
                p.getY() + 250 > y;
    }

    // =====================================================
    // GETTERS
    // =====================================================

    public int getX()
    {
        return x;
    }

    public int getY()
    {
        return y;
    }

    public int getSize()
    {
        return size;
    }
}
